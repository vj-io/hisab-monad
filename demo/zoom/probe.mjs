import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport:{width:1920,height:1080}, deviceScaleFactor:2 });
const p = await ctx.newPage();
await p.goto('https://hisab-monad.vercel.app',{waitUntil:'domcontentloaded'});
await p.getByText('Total assets').first().waitFor();
await p.waitForTimeout(1500);
const T=async(n,f)=>{const s=Date.now(); await f(); console.log(n,Date.now()-s)};
const tab=(n)=>p.getByRole('button',{name:n,exact:true}).first();
await T('trial tab', ()=>tab('Exporter').click({trial:true}));
await T('click tab', ()=>tab('Exporter').click());
await T('wait load btn', ()=>p.getByText('Load demo invoice').first().waitFor());
await T('trial load', ()=>p.getByRole('button',{name:'Load demo invoice',exact:true}).first().click({trial:true}));
await T('isEnabled', ()=>p.getByRole('button',{name:'Load demo invoice',exact:true}).first().isEnabled());
await T('buyer', async()=>{await tab('Buyer').click(); await p.getByText(/Invoice not found|Pay invoice/).first().waitFor();});
await T('email click', ()=>p.getByRole('button',{name:'Use email wallet'}).first().click());
await T('modal', ()=>p.locator('#privy-modal-content').waitFor());
const close = p.locator('#privy-modal-content button[aria-label="close modal"]').first();
await T('close count', ()=>close.count());
await T('close trial', ()=>close.click({trial:true}));
await T('close box', async()=>console.log(await close.boundingBox()));
await b.close();
